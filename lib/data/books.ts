export const getBook = (slug: string) => BOOKS.find((b) => b.slug === slug);

export function bookRows(b: Book): [string, string][] {
  return [
    ["Автор", b.author],
    ["Издание", `${b.city}${b.publisher ? `: ${b.publisher}` : ""}, ${b.year}. — ${b.pages} с.`],
    ...(b.isbn ? ([["ISBN", b.isbn]] as [string, string][]) : []),
    ...(b.extraRows ?? []),
  ];
}
