import re,sys
p=sys.argv[1]; t=open(p,encoding='utf-8').read()
heads=["Актуальность исследования","Объект исследования:","Предмет исследования:","Цель исследования:","Задачи исследования:","Гипотеза исследования:","Методологическая основа исследования:","Методы исследования:","Опытно-экспериментальная база:","Этапы исследования.","Научная новизна исследования.","Теоретическая значимость исследования:","Практическая значимость исследования:","Достоверность исследования","Апробация результатов и внедрение результатов исследования","Основные положения диссертации, выносимые на защиту:","Структура диссертации.","Основное содержание диссертации отражено в публикациях"]
out=[]
for chunk in t.split("\n\n"):
    done=False
    for h in heads:
        if chunk.startswith(h):
            title=h.rstrip(':.')
            if h=="Основное содержание диссертации отражено в публикациях": title="Публикации по теме диссертации"
            out.append("### "+title)
            rest=chunk[len(h):].strip() if h not in ("Достоверность исследования","Апробация результатов и внедрение результатов исследования","Основное содержание диссертации отражено в публикациях") else chunk
            if rest: out.append(rest[0].upper()+rest[1:] if rest[0].islower() and h not in("Достоверность исследования",) else rest)
            done=True;break
    if not done:
        if chunk.startswith("Во Введении") : out.append("### Введение"); 
        if chunk.startswith("В первой главе"): out.append("### Глава 1")
        if chunk.startswith("Во второй главе"): out.append("### Глава 2")
        if chunk.startswith("В заключении диссертации"): out.append("### Заключение")
        out.append(chunk)
open(p,'w',encoding='utf-8').write("\n\n".join(out))
