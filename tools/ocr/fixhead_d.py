import re,sys
p=sys.argv[1]; blocks=open(p,encoding='utf-8').read().split("\n\n")
CANON=[
 (r"^(#+ )?ВВЕДЕНИЕ$", "## Введение", 0),
 (r"^(#+ )?Глава 1\.", "## Глава 1. Исторический опыт и теоретические предпосылки развития профессионального образования в ювелирном искусстве", 0),
 (r"^(#+ )?1\.1\. Особенности зарождения", "### 1.1. Особенности зарождения, становления и развития профессионального образования в ювелирном искусстве", r"^профессионального образования в ювелирном искусстве\.?$"),
 (r"^(#+ )?1\.2\. Теоретические предпосылки", "### 1.2. Теоретические предпосылки развития профессионального образования в ювелирном искусстве", 0),
 (r"^(#+ )?Выводы по первой главе", "### 1.3. Выводы по первой главе", 0),
 (r"^(#+ )?Глава 2\.", "## Глава 2. Педагогическая модель современного профессионального образования в ювелирном искусстве", 0),
 (r"^(#+ )?2\.1\. Концептуальные основы", "### 2.1. Концептуальные основы современной педагогической модели профессионального образования в ювелирном искусстве", r"^профессионального образования в ювелирном искусстве\.?$"),
 (r"^(#+ )?2\.2\. Экспериментальная работа", "### 2.2. Экспериментальная работа по внедрению разработанной педагогической модели в современном образовании", 0),
 (r"^(#+ )?Выводы по второй главе", "### 2.3. Выводы по второй главе", 0),
 (r"^(#+ )?ЗАКЛЮЧЕНИЕ$", "## Заключение", 0),
 (r"^(#+ )?СПИСОК ЛИТЕРАТУРЫ$", "## Список литературы", 0),
 (r"^(#+ )?ПРИЛОЖЕНИЕ\.?$|^## Приложение$", "## Приложение", 0),
]
used=set(); out=[]; drop_next=None
for b in blocks:
    if drop_next and re.match(drop_next,b.strip()):
        drop_next=None; continue
    drop_next=None
    hit=False
    for i,(rx,canon,cont) in enumerate(CANON):
        if i not in used and re.match(rx,b.strip(),re.I):
            out.append(canon); used.add(i); hit=True; drop_next=cont or None; break
    if hit: continue
    if b.startswith("#"):
        b=re.sub(r"^#+\s*","",b)  # demote stray headings
    out.append(b)
missing=[CANON[i][1] for i in range(len(CANON)) if i not in used]
print("missing:",missing)
open(p,'w',encoding='utf-8').write("\n\n".join(out))
